export const TRANSLATIONS = { ar, en, fr, es, de, tr, ru, ur, hi, id, pt, zh };

// Guarantee every language has every key. Newly added strings are authored in
// Arabic + English; all other locales fall back to the English wording so no
// screen ever shows a missing-translation placeholder.
Object.keys(TRANSLATIONS).forEach((code) => {
  if (code === 'en') return;
  TRANSLATIONS[code] = { ...en, ...TRANSLATIONS[code] };
});

const RTL = ['ar', 'ur'];
const ALL_CODES = Object.keys(TRANSLATIONS);

export const normalizeLocale = (value) => {
  const code = String(value || '').toLowerCase().split('-')[0].trim();
  return ALL_CODES.includes(code) ? code : 'ar';
};

export const isRTL = (locale) => RTL.includes(normalizeLocale(locale));

/**
 * Keep labels readable on small Telegram screens. Icons are rendered by the
 * component that owns the action, so copy should not carry a second emoji.
 */
export const cleanDisplayText = (text = '') => String(text)
  .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\uFE0F\u200D]/gu, '')
  .replace(/\s{2,}/g, ' ')
  .trim();

/**
 * Fallback chain: requested locale → English → Arabic → the key itself.
 * No screen ever shows a missing-translation placeholder again.
 */
export const t = (locale, key, vars = {}) => {
  const dictionary = TRANSLATIONS[normalizeLocale(locale)] || TRANSLATIONS.ar;
  let value = dictionary[key] ?? TRANSLATIONS.en[key] ?? TRANSLATIONS.ar[key] ?? key;
  Object.entries(vars).forEach(([name, replacement]) => {
    value = value.replaceAll(`{${name}}`, String(replacement));
  });
  // Keep locale values such as `ar-IQ` intact while cleaning all UI labels.
  return key === 'dateLocale' ? value : cleanDisplayText(value);
};

export const localizedName = (item, locale) => {
  if (!item) return '';
  const loc = normalizeLocale(locale);
  return cleanDisplayText(loc === 'ar' ? (item.nameAr || item.name || '') : (item.name || item.nameAr || ''));
};

/**
 * Strip raw Markdown markers (**bold**, *italic*, `code`) from admin-configured
 * strings before rendering them as plain text — otherwise users see literal
 * asterisks like `**PANEL RESELLER**` in headers and titles.
 */
export const cleanMarkdown = (text = '') => cleanDisplayText(String(text)
  .replace(/\*\*(.+?)\*\*/g, '$1')
  .replace(/(^|[^*])\*([^*\n]+)\*/g, '$1$2')
  .replace(/`([^`\n]+)`/g, '$1'));
